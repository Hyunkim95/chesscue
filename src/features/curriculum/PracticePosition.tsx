import { cachedReflection } from "../../domain/material/reflection";
import { z } from "zod";
import { useEntryState } from "../../shared/navigation/history-entry";
import { Chess, type Move, type Square } from "chess.js";
import { useState } from "react";

import type { AssessPosition } from "../../application/analyze-game/assess-position";
import { scoreTransferAttempt } from "../../domain/analysis/review-training";
import type { PracticeExercise } from "../../domain/transfer/types";
import { TrainingBoard } from "../../shared/chess/TrainingBoard";
import {
  GuidedMoveFeedback,
  TrainingStage,
  type AnalyzeReply,
} from "../review/GuidedMoveFeedback";
import { RookExploration } from "../rook/RookExploration";

export function PracticePosition({
  exercise,
  gamePrompt,
  compact = false,
  analyzeReply,
  assessPosition,
  onRatedGame,
  onTrainingPlan,
  onAnotherPosition,
  onComplete,
}: {
  readonly exercise: PracticeExercise;
  readonly gamePrompt?:
    | { readonly moveLabel: string; readonly question: string }
    | undefined;
  readonly compact?: boolean;
  readonly analyzeReply: AnalyzeReply;
  readonly assessPosition: AssessPosition;
  readonly onRatedGame: () => void;
  readonly onTrainingPlan: () => void;
  readonly onAnotherPosition?: (() => void) | undefined;
  readonly onComplete: () => void;
}) {
  const [rookOpen, setRookOpen] = useState(false);
  const [selected, setSelected] = useState<Square | null>(null);
  const [promotion, setPromotion] = useState<Square | null>(null);
  const [played, setPlayed] = useEntryState(
    "practice.move:" + exercise.id,
    z
      .string()
      .regex(/^[a-h][1-8][a-h][1-8][qrbn]?$/)
      .nullable(),
    null,
  );
  const curriculumExercise = exercise.id.startsWith("archive-curriculum-");
  const libraryPuzzle = exercise.id.startsWith("archive-library-");
  const score = played ? scoreTransferAttempt(exercise, played) : null;
  const position = new Chess(exercise.fen);
  const white = position.turn() === "w";
  const choices =
    selected === null
      ? []
      : position.moves({ square: selected, verbose: true });
  const question =
    gamePrompt?.question ?? exercise.prompt ?? cachedReflection(exercise.theme);
  const source = exercise.authorship && exercise.source && (
    <small>
      Generated by {exercise.authorship.model} · Stockfish verified ·{" "}
      {"provenance" in exercise &&
      exercise.provenance === "Original ChessCue training position." ? (
        "Original ChessCue position"
      ) : (
        <a
          href={
            exercise.source.url.includes("/?sharedGame=")
              ? "?" + new URL(exercise.source.url).searchParams.toString()
              : exercise.source.url
          }
          target="_blank"
          rel="noreferrer"
        >
          Source game
        </a>
      )}
    </small>
  );
  if (compact) {
    return (
      <main className="content-shell review-page">
        <RookExploration
          fen={exercise.fen}
          orientation={white ? "white" : "black"}
          analyzeReply={analyzeReply}
          assessPosition={assessPosition}
          topic={exercise.theme}
          compact
          closeLabel="Back to Practice"
          onClose={onTrainingPlan}
          puzzle={{
            question,
            source,
            onMove: (uci) => {
              const { accepted } = scoreTransferAttempt(exercise, uci);
              if (played === null) setPlayed(uci);
              if (accepted) onComplete();
              return accepted;
            },
          }}
        />
      </main>
    );
  }
  const selectSquare = (square: Square) => {
    setPromotion(null);
    if (position.get(square)?.color === position.turn()) {
      setSelected(square);
      return;
    }
    if (selected === null) return;
    const moves = choices.filter((candidate) => candidate.to === square);
    if (moves.some((move) => move.promotion !== undefined)) {
      setPromotion(square);
      return;
    }
    const move = moves[0];
    if (move === undefined) return;
    playMove(move);
  };
  const playMove = (move: Move) => {
    setPromotion(null);
    const attempt = scoreTransferAttempt(exercise, move.lan);
    setPlayed(move.lan);
    if (attempt.accepted) onComplete();
  };
  return (
    <main className="content-shell review-page">
      <section className="game-review" aria-labelledby="practice-title">
        <header className="game-review__header">
          <div>
            <p className="game-review__eyebrow">
              {gamePrompt
                ? "Stockfish-verified drill from your game"
                : curriculumExercise
                  ? "ChessCue curriculum"
                  : libraryPuzzle
                    ? "Shared puzzle library"
                    : "From your learning plan"}
            </p>
            <h1 id="practice-title">
              {gamePrompt
                ? `Retry ${gamePrompt.moveLabel.toLowerCase()}`
                : curriculumExercise || libraryPuzzle
                  ? "Find the first move"
                  : "Try a similar position"}
            </h1>
            {source}
          </div>
        </header>
        {rookOpen && score !== null ? (
          <RookExploration
            fen={exercise.fen}
            orientation={white ? "white" : "black"}
            analyzeReply={analyzeReply}
            assessPosition={assessPosition}
            topic={exercise.theme}
            onClose={() => {
              setRookOpen(false);
            }}
          />
        ) : score === null ? (
          <TrainingStage
            board={
              <TrainingBoard
                fen={exercise.fen}
                orientation={white ? "white" : "black"}
                captures={[]}
                selectedSquare={selected}
                legalMoves={choices}
                promotionSquare={promotion}
                onSquareSelect={selectSquare}
                onPromote={playMove}
              />
            }
            eyebrow="Your move"
            title={question}
            description={white ? "White to move." : "Black to move."}
          >
            <button
              type="button"
              className="game-review__quiet-action"
              onClick={onTrainingPlan}
            >
              Back to training plan
            </button>
            <button
              type="button"
              className="game-review__quiet-action"
              onClick={onRatedGame}
            >
              Play a rated game
            </button>
          </TrainingStage>
        ) : (
          <GuidedMoveFeedback
            gameId={exercise.id}
            analyzeReply={analyzeReply}
            assessPosition={assessPosition}
            fen={exercise.fen}
            score={score}
            verifiedLine={exercise.verification.principalVariation}
            theme={exercise.theme}
            explanation={exercise.explanation}
            nextLabel={
              onAnotherPosition === undefined
                ? undefined
                : "Try another position"
            }
            {...(onAnotherPosition === undefined
              ? {}
              : { onNext: onAnotherPosition })}
            onFinish={onRatedGame}
            finishLabel="Play a rated game"
            onUndo={() => {
              setSelected(null);
              setPlayed(null);
            }}
          >
            <button
              type="button"
              className="review-action"
              onClick={() => {
                setRookOpen(true);
              }}
            >
              Explore with Rook
            </button>
            <button
              type="button"
              className="game-review__quiet-action"
              onClick={onTrainingPlan}
            >
              Back to training plan
            </button>
          </GuidedMoveFeedback>
        )}
      </section>
    </main>
  );
}
